//
//  SnapshottableMacroTests.swift
//  DogmaKit
//
//  Expansion and diagnostics of `@Snapshottable`. XCTest, because
//  `assertMacroExpansion` reports failures through `XCTFail`.
//

import XCTest
import SwiftSyntaxMacros
import SwiftSyntaxMacrosTestSupport
import DogmaKitMacros

private var macros: [String: Macro.Type] { [
    "Snapshottable": SnapshottableMacro.self,
    "SnapshotIgnored": SnapshotMarkerMacro.self,
    "SnapshotField": SnapshotMarkerMacro.self,
    "SnapshotNested": SnapshotMarkerMacro.self,
] }

final class SnapshottableMacroTests: XCTestCase {

    func testExpansion() {
        assertMacroExpansion(
            """
            @Snapshottable
            struct Node {
                public let id: Int
                @SnapshotIgnored public let attributes: Attributes
                /// Used CPU, tf.
                public var cpu: Double { 0 }
                @SnapshotNested public var charge: Charge? { nil }
                @SnapshotNested public var modules: Modules { Modules() }
                @SnapshotField public func tank() -> Tank { Tank() }
                public func capacitor() -> Result { Result() }
                public static var shared: Int { 0 }
                var entity: Entity { Entity() }
            }
            """,
            expandedSource: """
            struct Node {
                public let id: Int
                public let attributes: Attributes
                /// Used CPU, tf.
                public var cpu: Double { 0 }
                public var charge: Charge? { nil }
                public var modules: Modules { Modules() }
                public func tank() -> Tank { Tank() }
                public func capacitor() -> Result { Result() }
                public static var shared: Int { 0 }
                var entity: Entity { Entity() }

                /// Values of this node's read stats, detached from the engine: a plain value that
                /// outlives `DogmaEngine.evaluate` and can be sent across actors. Generated by
                /// `@Snapshottable`; see `snapshot()`.
                public struct Snapshot: Sendable, Equatable {
                    public let id: Int
                    /// Used CPU, tf.
                    public let cpu: Double
                    public let charge: Charge.Snapshot?
                    public let modules: Modules.Snapshot
                    public let tank: Tank
                }

                /// Copies this node's read stats into a `Snapshot`.
                public func snapshot() -> Snapshot {
                    Snapshot(
                        id: id,
                        cpu: cpu,
                        charge: charge?.snapshot(),
                        modules: modules.snapshot(),
                        tank: tank()
                    )
                }
            }
            """,
            macros: macros
        )
    }

    func testMissingType() {
        assertMacroExpansion(
            """
            @Snapshottable
            struct Node {
                public var cpu = 0.0
            }
            """,
            expandedSource: """
            struct Node {
                public var cpu = 0.0
            }
            """,
            diagnostics: [
                DiagnosticSpec(message: "'cpu' needs an explicit type to be part of the snapshot; mark it @SnapshotIgnored to exclude it",
                               line: 3, column: 16)
            ],
            macros: macros
        )
    }

    func testInvalidMethod() {
        assertMacroExpansion(
            """
            @Snapshottable
            struct Node {
                @SnapshotField public func dps(to target: Target) -> Double { 0 }
            }
            """,
            expandedSource: """
            struct Node {
                public func dps(to target: Target) -> Double { 0 }
            }
            """,
            diagnostics: [
                DiagnosticSpec(message: "'dps' must be a public instance method without parameters, 'async' or 'throws' to be a snapshot field",
                               line: 3, column: 32)
            ],
            macros: macros
        )
    }

    func testNotAStruct() {
        assertMacroExpansion(
            """
            @Snapshottable
            enum Node {
            }
            """,
            expandedSource: """
            enum Node {
            }
            """,
            diagnostics: [
                DiagnosticSpec(message: "@Snapshottable can only be applied to a struct", line: 1, column: 1)
            ],
            macros: macros
        )
    }
}
